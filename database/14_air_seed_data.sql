-- Create one schedule per day for the next 14 days. Each new flight has a dedicated
-- aircraft, so the aircraft-conflict trigger remains meaningful without seed overlaps.
INSERT INTO flight_schedules (flight_schedule_id, flight_id, aircraft_id, flight_date, schedule_status, overbook_limit)
SELECT 10000 + (f.flight_id - 100) * 14 + days.day_offset, f.flight_id, f.flight_id,
       DATE_ADD(CURDATE(), INTERVAL days.day_offset DAY),
       'SCHEDULED', 4
FROM flights f
CROSS JOIN (
  SELECT ones.n + tens.n * 10 + 1 AS day_offset
  FROM (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
        UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) ones
  CROSS JOIN (SELECT 0 AS n UNION ALL SELECT 1) tens
  WHERE ones.n + tens.n * 10 < 14
) days
WHERE f.flight_id BETWEEN 100 AND 147
  AND NOT EXISTS (
    SELECT 1 FROM flight_schedules existing
    WHERE existing.flight_id = f.flight_id
      AND existing.flight_date = DATE_ADD(CURDATE(), INTERVAL days.day_offset DAY)
  );

-- Ensure existing schedules also receive the expanded seat capacity after an upgrade.
-- Trigger-generated rows on new schedules are ignored because their seat numbers already exist.
INSERT IGNORE INTO flight_seats (flight_schedule_id, seat_no, cabin_class)
SELECT fs.flight_schedule_id, CONCAT('E', LPAD(seq.n, 2, '0')), 'ECONOMY'
FROM flight_schedules fs
JOIN aircraft ac ON ac.aircraft_id = fs.aircraft_id
CROSS JOIN (
  SELECT ones.n + tens.n * 10 + 1 AS n
  FROM (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
        UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) ones
  CROSS JOIN (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4) tens
  WHERE ones.n + tens.n * 10 < 48
) seq
WHERE seq.n <= ac.economy_seats;

INSERT IGNORE INTO flight_seats (flight_schedule_id, seat_no, cabin_class)
SELECT fs.flight_schedule_id, CONCAT('B', LPAD(seq.n, 2, '0')), 'BUSINESS'
FROM flight_schedules fs
JOIN aircraft ac ON ac.aircraft_id = fs.aircraft_id
CROSS JOIN (
  SELECT ones.n + tens.n * 10 + 1 AS n
