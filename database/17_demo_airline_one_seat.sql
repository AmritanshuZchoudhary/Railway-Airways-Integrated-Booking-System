-- Inventory for the two-tab "standby to confirmed" demonstration (airline).
-- Run after 09-15. This file creates NO accounts and NO tickets: you register two passengers
-- yourself, in two browser tabs, and book and cancel by hand (see docs/two_tab_upgrade_demo.md).
--
-- It adds one flight with exactly ONE economy seat and room for ONE standby passenger:
--   flight DS777, New Delhi -> Jaipur, two days from today, economy.
--   (Flight DS201 flies the same route that day with more seats; choose DS777 in the results.)
-- Re-running this file moves the flight to two days from today and clears the bookings made on it,
-- so the demonstration can be repeated.
USE airline_db;
SET @old_safe_updates = @@SQL_SAFE_UPDATES;
SET SQL_SAFE_UPDATES = 0;

INSERT INTO aircraft (aircraft_id, airline_id, registration_no, model, economy_seats, business_seats) VALUES
  (4, 1, 'VT-DS03', 'Demo One-Seat Jet', 1, 0)
ON DUPLICATE KEY UPDATE airline_id=VALUES(airline_id), registration_no=VALUES(registration_no), model=VALUES(model), economy_seats=VALUES(economy_seats), business_seats=VALUES(business_seats);

INSERT INTO flights (flight_id, flight_number, airline_id, origin_airport_id, destination_airport_id, departure_time, arrival_time, distance_km) VALUES
  (7, 'DS777', 1, 1, 3, '14:00:00', '15:10:00', 240.00)
ON DUPLICATE KEY UPDATE flight_number=VALUES(flight_number), airline_id=VALUES(airline_id), origin_airport_id=VALUES(origin_airport_id), destination_airport_id=VALUES(destination_airport_id), departure_time=VALUES(departure_time), arrival_time=VALUES(arrival_time), distance_km=VALUES(distance_km);

INSERT INTO fare_rules (flight_id, cabin_class, base_fare) VALUES
  (7, 'ECONOMY', 2800.00)
ON DUPLICATE KEY UPDATE base_fare=VALUES(base_fare);

-- The seat map (one seat, E01) is generated by trigger the first time the schedule is inserted.
INSERT INTO flight_schedules (flight_schedule_id, flight_id, aircraft_id, flight_date, schedule_status, overbook_limit) VALUES
  (2101, 7, 4, DATE_ADD(CURDATE(), INTERVAL 2 DAY), 'SCHEDULED', 1)
ON DUPLICATE KEY UPDATE flight_id=VALUES(flight_id), aircraft_id=VALUES(aircraft_id), flight_date=VALUES(flight_date), schedule_status=VALUES(schedule_status), overbook_limit=VALUES(overbook_limit);

-- Reset: remove earlier bookings made on schedule 2101 (child rows first).
DROP PROCEDURE IF EXISTS sp_demo_reset_airline_one_seat;
DELIMITER $$
CREATE PROCEDURE sp_demo_reset_airline_one_seat()
BEGIN
  UPDATE railway_db.users u
  JOIN (SELECT passenger_id, SUM(points) AS earned FROM transport_core.loyalty_txn
        WHERE air_booking_id IN (SELECT air_booking_id FROM air_bookings WHERE flight_schedule_id = 2101)
        GROUP BY passenger_id) x ON x.passenger_id = u.user_id
  SET u.loyalty_points = GREATEST(CAST(u.loyalty_points AS SIGNED) - x.earned, 0);
  DELETE FROM transport_core.loyalty_txn
  WHERE air_booking_id IN (SELECT air_booking_id FROM air_bookings WHERE flight_schedule_id = 2101);

  DELETE FROM baggage WHERE air_booking_id IN (SELECT air_booking_id FROM air_bookings WHERE flight_schedule_id = 2101);
  DELETE FROM air_booking_history WHERE air_booking_id IN (SELECT air_booking_id FROM air_bookings WHERE flight_schedule_id = 2101);
  DELETE FROM air_standby_entries WHERE flight_schedule_id = 2101;
  DELETE FROM air_cancellations WHERE flight_schedule_id = 2101;
  DELETE FROM air_seat_allocations WHERE flight_schedule_id = 2101;
  DELETE FROM air_bookings WHERE flight_schedule_id = 2101;
END$$
DELIMITER ;
CALL sp_demo_reset_airline_one_seat();
DROP PROCEDURE sp_demo_reset_airline_one_seat;

SET SQL_SAFE_UPDATES = @old_safe_updates;

SELECT fs.flight_schedule_id, f.flight_number, fs.flight_date, f.departure_time, fs.overbook_limit,
       (SELECT COUNT(*) FROM flight_seats s WHERE s.flight_schedule_id = fs.flight_schedule_id AND s.cabin_class = 'ECONOMY') AS economy_seats,
       (SELECT COUNT(*) FROM air_bookings b WHERE b.flight_schedule_id = fs.flight_schedule_id) AS bookings_now
FROM flight_schedules fs
JOIN flights f ON f.flight_id = fs.flight_id
WHERE fs.flight_schedule_id = 2101;
