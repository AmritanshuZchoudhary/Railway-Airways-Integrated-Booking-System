-- Airline Management System (air booking module)
-- Target: MySQL Community Server 8.0+
-- Run AFTER 01-08 (the railway files). The airline module lives in its own database,
-- `airline_db`, so the railway and airline tables stay separate. The only link to the
-- railway side is the shared passenger account (railway_db.users).
CREATE DATABASE IF NOT EXISTS airline_db
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_0900_ai_ci;
USE airline_db;

CREATE TABLE IF NOT EXISTS airlines (
  airline_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  iata_code VARCHAR(3) NOT NULL,
  airline_name VARCHAR(120) NOT NULL,
  PRIMARY KEY (airline_id),
  UNIQUE KEY uq_airlines_iata (iata_code)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS airports (
  airport_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  iata_code VARCHAR(3) NOT NULL,
  airport_name VARCHAR(120) NOT NULL,
  city VARCHAR(100) NOT NULL,
  PRIMARY KEY (airport_id),
  UNIQUE KEY uq_airports_iata (iata_code),
  UNIQUE KEY uq_airports_name_city (airport_name, city)
) ENGINE=InnoDB;

-- Fleet. Seat counts per cabin are used to generate the seat map of every flight schedule.
CREATE TABLE IF NOT EXISTS aircraft (
  aircraft_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  airline_id BIGINT UNSIGNED NOT NULL,
  registration_no VARCHAR(12) NOT NULL,
  model VARCHAR(60) NOT NULL,
  economy_seats SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  business_seats SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (aircraft_id),
  UNIQUE KEY uq_aircraft_registration (registration_no),
  KEY idx_aircraft_airline (airline_id),
  CONSTRAINT fk_aircraft_airline FOREIGN KEY (airline_id) REFERENCES airlines (airline_id),
  CONSTRAINT chk_aircraft_seats CHECK (economy_seats + business_seats > 0)
) ENGINE=InnoDB;

-- A direct (non-stop) flight with fixed daily times.
CREATE TABLE IF NOT EXISTS flights (
  flight_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  flight_number VARCHAR(8) NOT NULL,
  airline_id BIGINT UNSIGNED NOT NULL,
  origin_airport_id BIGINT UNSIGNED NOT NULL,
  destination_airport_id BIGINT UNSIGNED NOT NULL,
  departure_time TIME NOT NULL,
  arrival_time TIME NOT NULL,
  distance_km DECIMAL(8,2) NULL,
  PRIMARY KEY (flight_id),
  UNIQUE KEY uq_flights_number (flight_number),
  KEY idx_flights_route (origin_airport_id, destination_airport_id),
  CONSTRAINT fk_flights_airline FOREIGN KEY (airline_id) REFERENCES airlines (airline_id),
  CONSTRAINT fk_flights_origin FOREIGN KEY (origin_airport_id) REFERENCES airports (airport_id),
  CONSTRAINT fk_flights_destination FOREIGN KEY (destination_airport_id) REFERENCES airports (airport_id),
  CONSTRAINT chk_flight_airports_differ CHECK (origin_airport_id <> destination_airport_id),
  CONSTRAINT chk_flight_distance CHECK (distance_km IS NULL OR distance_km > 0)
) ENGINE=InnoDB;

-- Lookup table used by the dynamic fare function (novelty A1).
CREATE TABLE IF NOT EXISTS fare_rules (
  flight_id BIGINT UNSIGNED NOT NULL,
  cabin_class ENUM('ECONOMY', 'BUSINESS') NOT NULL,
  base_fare DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (flight_id, cabin_class),
  CONSTRAINT fk_fare_rules_flight FOREIGN KEY (flight_id) REFERENCES flights (flight_id),
  CONSTRAINT chk_fare_rule_base CHECK (base_fare > 0)
) ENGINE=InnoDB;

-- One dated run of a flight with its assigned aircraft. overbook_limit is the number of
-- extra STANDBY bookings (per cabin) accepted after the seats are full (novelty A2).
CREATE TABLE IF NOT EXISTS flight_schedules (
  flight_schedule_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  flight_id BIGINT UNSIGNED NOT NULL,
  aircraft_id BIGINT UNSIGNED NOT NULL,
  flight_date DATE NOT NULL,
  schedule_status ENUM('SCHEDULED', 'DELAYED', 'CANCELLED', 'DEPARTED') NOT NULL DEFAULT 'SCHEDULED',
  overbook_limit SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (flight_schedule_id),
  UNIQUE KEY uq_flight_date (flight_id, flight_date),
  KEY idx_schedule_date_status (flight_date, schedule_status),
  KEY idx_schedule_aircraft (aircraft_id, flight_date),
  CONSTRAINT fk_fschedules_flight FOREIGN KEY (flight_id) REFERENCES flights (flight_id),
  CONSTRAINT fk_fschedules_aircraft FOREIGN KEY (aircraft_id) REFERENCES aircraft (aircraft_id)
) ENGINE=InnoDB;

-- Seat map of one flight schedule. Rows are generated by trigger trg_air_schedule_generate_seats.
CREATE TABLE IF NOT EXISTS flight_seats (
  flight_seat_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  flight_schedule_id BIGINT UNSIGNED NOT NULL,
  seat_no VARCHAR(6) NOT NULL,
  cabin_class ENUM('ECONOMY', 'BUSINESS') NOT NULL,
  PRIMARY KEY (flight_seat_id),
  UNIQUE KEY uq_schedule_seat_no (flight_schedule_id, seat_no),
  KEY idx_fseats_schedule_cabin (flight_schedule_id, cabin_class),
  CONSTRAINT fk_fseats_schedule FOREIGN KEY (flight_schedule_id) REFERENCES flight_schedules (flight_schedule_id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- One booking = one passenger. passenger_id is the shared account in railway_db.users.
-- The standby position is derived from air_standby_entries (see vw_air_booking_overview).
CREATE TABLE IF NOT EXISTS air_bookings (
  air_booking_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  passenger_id BIGINT UNSIGNED NOT NULL,
  flight_schedule_id BIGINT UNSIGNED NOT NULL,
  cabin_class ENUM('ECONOMY', 'BUSINESS') NOT NULL,
  status ENUM('CONFIRMED', 'STANDBY', 'CANCELLED') NOT NULL,
  fare DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  refund_amount DECIMAL(10,2) NULL,
  booking_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (air_booking_id),
  KEY idx_air_bookings_passenger_time (passenger_id, booking_time),
  KEY idx_air_bookings_schedule_status (flight_schedule_id, status),
  CONSTRAINT fk_air_bookings_passenger FOREIGN KEY (passenger_id) REFERENCES railway_db.users (user_id),
  CONSTRAINT fk_air_bookings_schedule FOREIGN KEY (flight_schedule_id) REFERENCES flight_schedules (flight_schedule_id),
  CONSTRAINT chk_air_booking_fare CHECK (fare >= 0),
  CONSTRAINT chk_air_booking_refund CHECK (refund_amount IS NULL OR refund_amount >= 0)
) ENGINE=InnoDB;

-- Current allocations only. Released allocations are deleted; the history table and
-- air_cancellations keep the audit trail (same convention as the railway module).
CREATE TABLE IF NOT EXISTS air_seat_allocations (
  allocation_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  flight_schedule_id BIGINT UNSIGNED NOT NULL,
  flight_seat_id BIGINT UNSIGNED NOT NULL,
  air_booking_id BIGINT UNSIGNED NOT NULL,
  allocated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (allocation_id),
  UNIQUE KEY uq_air_schedule_seat (flight_schedule_id, flight_seat_id),
  UNIQUE KEY uq_air_booking_allocation (air_booking_id),
  CONSTRAINT fk_air_alloc_schedule FOREIGN KEY (flight_schedule_id) REFERENCES flight_schedules (flight_schedule_id),
  CONSTRAINT fk_air_alloc_seat FOREIGN KEY (flight_seat_id) REFERENCES flight_seats (flight_seat_id),
  CONSTRAINT fk_air_alloc_booking FOREIGN KEY (air_booking_id) REFERENCES air_bookings (air_booking_id)
) ENGINE=InnoDB;

-- Priority standby queue (novelty A2). priority_score: GOLD 3, SILVER 2, BASIC 1.
-- Order of service: priority_score DESC, queued_at ASC, standby_id ASC.
CREATE TABLE IF NOT EXISTS air_standby_entries (
  standby_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  air_booking_id BIGINT UNSIGNED NOT NULL,
  flight_schedule_id BIGINT UNSIGNED NOT NULL,
  cabin_class ENUM('ECONOMY', 'BUSINESS') NOT NULL,
  priority_score TINYINT UNSIGNED NOT NULL DEFAULT 1,
  status ENUM('WAITING', 'PROMOTED', 'CANCELLED') NOT NULL DEFAULT 'WAITING',
  queued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  promoted_at TIMESTAMP NULL DEFAULT NULL,
  PRIMARY KEY (standby_id),
  UNIQUE KEY uq_standby_booking (air_booking_id),
  KEY idx_standby_next (flight_schedule_id, cabin_class, status, priority_score, queued_at),
  CONSTRAINT fk_standby_booking FOREIGN KEY (air_booking_id) REFERENCES air_bookings (air_booking_id),
  CONSTRAINT fk_standby_schedule FOREIGN KEY (flight_schedule_id) REFERENCES flight_schedules (flight_schedule_id),
  CONSTRAINT chk_standby_priority CHECK (priority_score BETWEEN 1 AND 3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS air_cancellations (
  cancellation_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  air_booking_id BIGINT UNSIGNED NOT NULL,
  flight_schedule_id BIGINT UNSIGNED NOT NULL,
  cabin_class ENUM('ECONOMY', 'BUSINESS') NOT NULL,
  released_flight_seat_id BIGINT UNSIGNED NULL,
  refund_amount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  cancelled_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reason VARCHAR(255) NULL,
  PRIMARY KEY (cancellation_id),
  UNIQUE KEY uq_air_cancellation_booking (air_booking_id),
  KEY idx_air_cancellations_schedule (flight_schedule_id, cancelled_at),
  CONSTRAINT fk_air_cancellations_booking FOREIGN KEY (air_booking_id) REFERENCES air_bookings (air_booking_id),
  CONSTRAINT fk_air_cancellations_schedule FOREIGN KEY (flight_schedule_id) REFERENCES flight_schedules (flight_schedule_id),
  CONSTRAINT fk_air_cancellations_seat FOREIGN KEY (released_flight_seat_id) REFERENCES flight_seats (flight_seat_id),
  CONSTRAINT chk_air_cancellation_refund CHECK (refund_amount >= 0)
) ENGINE=InnoDB;

-- Status-change audit trail, written by trigger trg_air_bookings_after_insert/update.
CREATE TABLE IF NOT EXISTS air_booking_history (
  history_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  air_booking_id BIGINT UNSIGNED NOT NULL,
  old_status ENUM('CONFIRMED', 'STANDBY', 'CANCELLED') NULL,
  new_status ENUM('CONFIRMED', 'STANDBY', 'CANCELLED') NOT NULL,
  event_type ENUM('BOOKED', 'STANDBY_JOINED', 'PROMOTED', 'CANCELLED') NOT NULL,
  event_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (history_id),
  KEY idx_air_history_booking (air_booking_id, event_time),
  CONSTRAINT fk_air_history_booking FOREIGN KEY (air_booking_id) REFERENCES air_bookings (air_booking_id)
) ENGINE=InnoDB;

-- Weak entity: a bag has no meaning without its booking (key: air_booking_id + bag_no).
-- excess_fee is set by trigger trg_air_baggage_before_insert (novelty A3).
-- Historical standby observations used by the airline confirmation estimator.
-- Synthetic demo rows and finalized application outcomes are stored separately.
CREATE TABLE IF NOT EXISTS air_waitlist_probability_history (
  history_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  source_air_booking_id BIGINT UNSIGNED NULL,
  origin_airport_id BIGINT UNSIGNED NOT NULL,
  destination_airport_id BIGINT UNSIGNED NOT NULL,
  cabin_class ENUM('ECONOMY', 'BUSINESS') NOT NULL,
  standby_position_at_observation INT UNSIGNED NOT NULL,
  days_remaining_at_observation INT UNSIGNED NOT NULL,
  final_outcome ENUM('CONFIRMED', 'NOT_CONFIRMED', 'PASSENGER_CANCELLED') NOT NULL,
  observation_date DATE NOT NULL,
  data_source ENUM('SIMULATED_DEMO', 'RECORDED_OUTCOME') NOT NULL DEFAULT 'SIMULATED_DEMO',
  PRIMARY KEY (history_id),
  UNIQUE KEY uq_air_probability_source_booking (source_air_booking_id),
  KEY idx_air_probability_lookup (origin_airport_id, destination_airport_id, cabin_class, standby_position_at_observation, days_remaining_at_observation),
  KEY idx_air_probability_fallback (cabin_class, standby_position_at_observation, final_outcome),
  CONSTRAINT fk_air_probability_source_booking FOREIGN KEY (source_air_booking_id) REFERENCES air_bookings (air_booking_id),
  CONSTRAINT fk_air_probability_origin FOREIGN KEY (origin_airport_id) REFERENCES airports (airport_id),
  CONSTRAINT fk_air_probability_destination FOREIGN KEY (destination_airport_id) REFERENCES airports (airport_id),
  CONSTRAINT chk_air_probability_airports_differ CHECK (origin_airport_id <> destination_airport_id),
  CONSTRAINT chk_air_probability_position CHECK (standby_position_at_observation > 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS baggage (
  air_booking_id BIGINT UNSIGNED NOT NULL,
  bag_no TINYINT UNSIGNED NOT NULL,
  weight_kg DECIMAL(5,2) NOT NULL,
  excess_fee DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (air_booking_id, bag_no),
  CONSTRAINT fk_baggage_booking FOREIGN KEY (air_booking_id) REFERENCES air_bookings (air_booking_id) ON DELETE CASCADE,
  CONSTRAINT chk_baggage_weight CHECK (weight_kg > 0 AND weight_kg <= 50),
  CONSTRAINT chk_baggage_fee CHECK (excess_fee >= 0)
) ENGINE=InnoDB;
