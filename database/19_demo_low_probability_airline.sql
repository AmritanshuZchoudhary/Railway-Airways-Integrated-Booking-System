-- Reset first: remove earlier bookings made on schedules 2102-2104 (child rows first), so that the
-- schedules can be moved to a new date.
DROP PROCEDURE IF EXISTS sp_demo_reset_airline_low_probability;
DELIMITER $$
CREATE PROCEDURE sp_demo_reset_airline_low_probability()
BEGIN
  UPDATE railway_db.users u
  JOIN (SELECT passenger_id, SUM(points) AS earned FROM transport_core.loyalty_txn
        WHERE air_booking_id IN (SELECT air_booking_id FROM air_bookings WHERE flight_schedule_id IN (2102, 2103, 2104))
        GROUP BY passenger_id) x ON x.passenger_id = u.user_id
  SET u.loyalty_points = GREATEST(CAST(u.loyalty_points AS SIGNED) - x.earned, 0);
  DELETE FROM transport_core.loyalty_txn
  WHERE air_booking_id IN (SELECT air_booking_id FROM air_bookings WHERE flight_schedule_id IN (2102, 2103, 2104));

  DELETE FROM baggage WHERE air_booking_id IN (SELECT air_booking_id FROM air_bookings WHERE flight_schedule_id IN (2102, 2103, 2104));
  DELETE FROM air_booking_history WHERE air_booking_id IN (SELECT air_booking_id FROM air_bookings WHERE flight_schedule_id IN (2102, 2103, 2104));
  DELETE FROM air_standby_entries WHERE flight_schedule_id IN (2102, 2103, 2104);
  DELETE FROM air_cancellations WHERE flight_schedule_id IN (2102, 2103, 2104);
  DELETE FROM air_seat_allocations WHERE flight_schedule_id IN (2102, 2103, 2104);
  DELETE FROM air_bookings WHERE flight_schedule_id IN (2102, 2103, 2104);
END$$
DELIMITER ;
CALL sp_demo_reset_airline_low_probability();
DROP PROCEDURE sp_demo_reset_airline_low_probability;

